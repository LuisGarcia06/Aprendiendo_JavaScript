// Declaramos una variable llamada "puntaje" y le asignamos el valor numérico 232
const puntaje = 232;

// Comparamos si "puntaje" es igual a 1000
if (puntaje == 1000) {
    // Este bloque se ejecuta SI la condición es verdadera (232 == 1000)
    console.log('Si es igual...');
}
else {
    // Este bloque se ejecuta si la condición es FALSA
    // Como 232 NO es igual a 1000, este es el que se ejecutará
    console.log('No es igual...');
}

// Resultado en consola: "No es igual..."


