// Declaración de función tradicional
// Esta función suma 2+2 y muestra el resultado en consola
function sumar() {
    console.log(2+2); // Imprime: 4
}

// Llamada a la función sumar
sumar();


// Expresión de función asignada a una constante
// Esta es otra forma de crear funciones en JavaScript
const sumar2 = function () {
    console.log(3+3) // Imprime: 6
}

// Llamada a la función sumar2
sumar2();


